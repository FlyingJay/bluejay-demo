#!/usr/bin/env node
/**
 * Emits the server's data catalog, functions/_data_catalog.json: every
 * tenant collection in security/collections.json (an entry with no `kind`,
 * or `kind: "tenant"`), with the apps that own it, whether it is
 * ownerScoped or on the audit trail, and the fields an export of it leaves
 * out (`redact`). Group Admin's Data & privacy section
 * (functions/_data_governance.js) lists, counts and exports a group's data
 * from it, so a collection added to the table shows up there with no list
 * to maintain.
 *
 * Only tenant collections are listed: they are the ones a group's admins
 * read under the rules (their apps' :admin tier in the group). Server,
 * platform, personal and public collections are left out, so an export
 * never reaches data the rules keep from the group's admins.
 *
 * `redact` is the entry's `auditRedact` plus every field the entry names
 * (serverFields and the field locks) that looks like a secret
 * (SECRET_FIELD). The export also drops any column whose name has a
 * secret-looking word, at run time (_data_governance.js), for fields the
 * table never names.
 *
 * Run through security/generate.js (which writes it, and checks it with --check).
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const JSON_PATH = path.join(ROOT, 'functions', '_data_catalog.json');

/** A field name that looks like it holds a secret. */
const SECRET_FIELD = /token|secret|hash|password|nonce/i;
/** Table keys whose value is a list of top-level field names. */
const FIELD_LIST_KEYS = ['serverFields', 'immutable', 'creatorOnly', 'ownerOnly', 'adminOnly', 'readerMayUpdate'];

/** Whether [entry] is kind tenant (the default kind). */
function isTenant(entry) {
  return !entry.kind || entry.kind === 'tenant';
}

/** The fields an export of [entry] leaves out, sorted. */
function redactedFields(entry) {
  const named = FIELD_LIST_KEYS.flatMap((key) => (Array.isArray(entry[key]) ? entry[key] : []))
    .filter((field) => typeof field === 'string' && SECRET_FIELD.test(field));
  const audit = Array.isArray(entry.auditRedact) ? entry.auditRedact : [];
  return [...new Set([...audit, ...named])].sort();
}

/** { collection: {apps, ownerScoped, auditTrail, redact} } for every tenant collection, sorted. */
function dataCatalog(table) {
  return Object.fromEntries(Object.entries(table.collections)
    .filter(([, entry]) => isTenant(entry))
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, entry]) => [name, {
      apps: Array.isArray(entry.apps) ? [...entry.apps] : [],
      ownerScoped: entry.ownerScoped === true,
      auditTrail: entry.auditTrail === true,
      redact: redactedFields(entry),
    }]));
}

function renderJson(table) {
  return `${JSON.stringify({
    comment: 'GENERATED by security/generate.js (security/generate_data_catalog.js) from security/collections.json. Do not edit: change the table and run `node security/generate.js`.',
    collections: dataCatalog(table),
  }, null, 2)}\n`;
}

/** Writes (or with --check, verifies) the catalog. */
function main(table, argv = []) {
  const next = renderJson(table);
  const current = fs.existsSync(JSON_PATH) ? fs.readFileSync(JSON_PATH, 'utf8') : null;
  if (argv.includes('--check')) {
    if (current !== next) {
      console.error(`${path.relative(ROOT, JSON_PATH)} is out of date with security/collections.json. Run \`node security/generate.js\` and commit the result.`);
      process.exitCode = 1;
    }
    return;
  }
  if (current !== next) {
    fs.writeFileSync(JSON_PATH, next);
    console.log(`${path.relative(ROOT, JSON_PATH)} regenerated.`);
  }
}

module.exports = { JSON_PATH, SECRET_FIELD, FIELD_LIST_KEYS, isTenant, redactedFields, dataCatalog, renderJson, main };
