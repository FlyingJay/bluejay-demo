#!/usr/bin/env node
/**
 * Whether a package's node_modules matches its package-lock.json, so the Node
 * suite never runs against dependencies from another commit. A node_modules
 * borrowed from an older checkout (symlinked, or left over from before a
 * lockfile change) makes tests fail that pass in CI: firebase-functions 5 in
 * place of 7 failed 29 tests on a clean origin/main.
 *
 * Checked per directory:
 *   missing  no node_modules
 *   linked   node_modules is a symlink, so it belongs to another checkout
 *   stale    a direct dependency's installed version isn't the locked one
 *
 * Only direct dependencies are compared: that catches a lockfile change
 * without reading every package, and platform-specific optional packages
 * (sharp's per-OS builds) are rightly absent.
 *
 * Usage: node scripts/ci/node_modules_state.js [--fix] <dir>...
 *   Prints each directory's problem and exits 1 if any. With --fix it
 *   reinstalls those directories with `npm ci` instead (a symlink is removed
 *   first; its target is left alone) and exits 1 only if an install fails.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

/**
 * The state of `dir`'s node_modules: `{ok: true}`, or `{ok: false, reason,
 * detail}` with reason 'missing' | 'linked' | 'stale'. A directory without a
 * package-lock.json is ok (nothing to compare against).
 */
function nodeModulesState(dir) {
  const lock = readJson(path.join(dir, 'package-lock.json'));
  if (!lock || !lock.packages) return { ok: true };
  const modules = path.join(dir, 'node_modules');
  let stat;
  try {
    stat = fs.lstatSync(modules);
  } catch {
    return { ok: false, reason: 'missing', detail: 'no node_modules' };
  }
  if (stat.isSymbolicLink()) {
    return { ok: false, reason: 'linked', detail: `node_modules links to ${fs.readlinkSync(modules)}` };
  }
  const root = lock.packages[''] || {};
  const optional = new Set(Object.keys(root.optionalDependencies || {}));
  const names = new Set([
    ...Object.keys(root.dependencies || {}),
    ...Object.keys(root.devDependencies || {}),
    ...optional,
  ]);
  const mismatches = [];
  for (const name of [...names].sort()) {
    const locked = lock.packages[`node_modules/${name}`];
    if (!locked || !locked.version) continue;
    const installed = readJson(path.join(modules, name, 'package.json'));
    if (!installed) {
      if (!optional.has(name) && !locked.optional) mismatches.push(`${name} not installed (locked ${locked.version})`);
    } else if (installed.version !== locked.version) {
      mismatches.push(`${name} ${installed.version} installed, ${locked.version} locked`);
    }
  }
  if (mismatches.length) return { ok: false, reason: 'stale', detail: mismatches.join('; ') };
  return { ok: true };
}

function install(dir, state) {
  if (state.reason === 'linked') fs.unlinkSync(path.join(dir, 'node_modules'));
  console.log(`Installing ${dir}/node_modules (${state.detail})`);
  const r = spawnSync('npm', ['ci', '--no-audit', '--no-fund'], { cwd: dir, stdio: ['ignore', 'ignore', 'inherit'] });
  return r.status === 0;
}

function main(argv) {
  const fix = argv.includes('--fix');
  const dirs = argv.filter((a) => a !== '--fix');
  if (!dirs.length) {
    console.error('Usage: node_modules_state.js [--fix] <dir>...');
    return 2;
  }
  let failed = false;
  for (const dir of dirs) {
    const state = nodeModulesState(dir);
    if (state.ok) continue;
    if (fix) {
      if (!install(dir, state)) failed = true;
    } else {
      console.error(`${dir}: ${state.reason}: ${state.detail}. Run \`npm ci\` in ${dir}.`);
      failed = true;
    }
  }
  return failed ? 1 : 0;
}

module.exports = { nodeModulesState };

if (require.main === module) process.exit(main(process.argv.slice(2)));
