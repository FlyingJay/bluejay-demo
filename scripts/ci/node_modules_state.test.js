'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { nodeModulesState } = require('./node_modules_state');

function pkgDir({ lock = {}, installed = null } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'nm-state-'));
  const packages = { '': lock.root || {} };
  for (const [name, entry] of Object.entries(lock.deps || {})) packages[`node_modules/${name}`] = entry;
  fs.writeFileSync(path.join(dir, 'package-lock.json'), JSON.stringify({ lockfileVersion: 3, packages }));
  if (installed) {
    for (const [name, version] of Object.entries(installed)) {
      fs.mkdirSync(path.join(dir, 'node_modules', name), { recursive: true });
      fs.writeFileSync(path.join(dir, 'node_modules', name, 'package.json'), JSON.stringify({ name, version }));
    }
  }
  return dir;
}

const LOCK = {
  root: { dependencies: { 'firebase-functions': '~7.2.2', '@scope/lib': '^1.0.0' }, devDependencies: { mocha: '^10.0.0' } },
  deps: {
    'firebase-functions': { version: '7.2.2' },
    '@scope/lib': { version: '1.4.0' },
    mocha: { version: '10.2.0', dev: true },
  },
};

test('matching direct dependencies are ok', () => {
  const dir = pkgDir({ lock: LOCK, installed: { 'firebase-functions': '7.2.2', '@scope/lib': '1.4.0', mocha: '10.2.0' } });
  assert.deepEqual(nodeModulesState(dir), { ok: true });
});

test('a direct dependency at another version is stale', () => {
  const dir = pkgDir({ lock: LOCK, installed: { 'firebase-functions': '5.1.1', '@scope/lib': '1.4.0', mocha: '10.2.0' } });
  const state = nodeModulesState(dir);
  assert.equal(state.reason, 'stale');
  assert.match(state.detail, /firebase-functions 5\.1\.1 installed, 7\.2\.2 locked/);
});

test('a missing direct dependency is stale; a missing optional one is not', () => {
  const lock = { root: { ...LOCK.root, optionalDependencies: { fsevents: '^2.0.0' } }, deps: { ...LOCK.deps, fsevents: { version: '2.3.3', optional: true } } };
  const dir = pkgDir({ lock, installed: { 'firebase-functions': '7.2.2', mocha: '10.2.0' } });
  const state = nodeModulesState(dir);
  assert.equal(state.reason, 'stale');
  assert.equal(state.detail, '@scope/lib not installed (locked 1.4.0)');
});

test('no node_modules is missing', () => {
  assert.equal(nodeModulesState(pkgDir({ lock: LOCK })).reason, 'missing');
});

test('a symlinked node_modules is linked, even when its versions match', () => {
  const other = pkgDir({ lock: LOCK, installed: { 'firebase-functions': '7.2.2', '@scope/lib': '1.4.0', mocha: '10.2.0' } });
  const dir = pkgDir({ lock: LOCK });
  fs.symlinkSync(path.join(other, 'node_modules'), path.join(dir, 'node_modules'));
  assert.equal(nodeModulesState(dir).reason, 'linked');
});

test('a directory without a lockfile is ok', () => {
  assert.deepEqual(nodeModulesState(fs.mkdtempSync(path.join(os.tmpdir(), 'nm-state-'))), { ok: true });
});
